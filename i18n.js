// Core Translation Function
function t(key, lang = null) {
  const currentLang = lang || (window.state ? window.state.language : 'mr');
  if (I18N_DATA[key] && I18N_DATA[key][currentLang]) {
    return I18N_DATA[key][currentLang];
  }
  return key;
}

// Function to apply translations to DOM
function applyTranslations(lang) {
  if (!lang) lang = 'mr';
  document.documentElement.lang = lang;

  // Translate all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (I18N_DATA[key] && I18N_DATA[key][lang]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = I18N_DATA[key][lang];
      } else {
        el.innerHTML = I18N_DATA[key][lang];
      }
    }
  });

  // Translate all input placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (I18N_DATA[key] && I18N_DATA[key][lang]) {
      el.placeholder = I18N_DATA[key][lang];
    }
  });

  // Update language pill active states across the page
  document.querySelectorAll('.lang-pill-btn, .lang-btn').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang') || (btn.textContent.includes('मराठी') ? 'mr' : btn.textContent.includes('हिंदी') ? 'hi' : 'en');
    if (btnLang === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Dispatch custom event for app.js dynamic components
  window.dispatchEvent(new CustomEvent('onionLanguageChanged', { detail: { lang } }));
}

window.I18N_DATA = I18N_DATA;
window.CHATBOT_RESPONSES = CHATBOT_RESPONSES;
window.t = t;
window.applyTranslations = applyTranslations;
